/** One sheet frame per slot, named by `ThornCastFrame`, drawn in that slot's palette. */
function framesOf(size: keyof Face): NamedFrame[] {
  return CHARACTER_IDS.map((character) => ({
    name: ThornCastFrame[character],
    palette: ThornwoodPalette[character],
    rows: FACES[character][size],
  }));
}

/** The portrait and head sheets, one frame per slot in each, named by `ThornCastFrame`. */
export const THORNWOOD_FACE_SHEETS: readonly ArtSheet<string>[] = [
  { key: ThornTex.heads, frames: framesOf('head') },
  { key: ThornTex.portraits, frames: framesOf('portrait') },
];
